    @Override
    public void close() {
        asyncExecutor.shutdown();
        if (dataSource == null) return;
        try {
            dataSource.getClass().getMethod("dispose").invoke(dataSource);
        } catch (ReflectiveOperationException e) {
            plugin.getLogger().log(Level.WARNING, "Ошибка закрытия пула подключений", e);
        }
    }

    private AuctionItem readItem(ResultSet rs) throws Exception {
        ItemStack item = deserialize(rs.getString("item"));
        int amount = rs.getInt("amount");
        if (amount > 0) {
            item.setAmount(amount);
        }
        AuctionLotType type = AuctionLotType.valueOf(rs.getString("lot_type"));
        List<ItemStack> inventoryContents = deserializeInventory(rs.getString("inventory_data"));
        String opId = null;
        long startedAt = 0L;
        try {
            opId = rs.getString("operation_id");
            startedAt = rs.getLong("processing_started_at");
        } catch (SQLException ignored) {}
        BigDecimal priceBd = rs.getBigDecimal("price");
        double price = priceBd != null ? priceBd.doubleValue() : 0.0;
        return new AuctionItem(
                rs.getLong("id"),
                rs.getString("seller_name"),
                AuctionCurrency.valueOf(rs.getString("currency")),
                item,
                price,
                rs.getLong("created_at"),
                AuctionStatus.fromInt(rs.getInt("status")),
                type,
                inventoryContents,
                opId,
                startedAt
        );
    }

    private String serializeInventory(List<ItemStack> contents) {
        if (contents == null || contents.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < contents.size(); i++) {
            if (i > 0) {
                sb.append(";");
            }
            ItemStack is = contents.get(i);
            sb.append(is == null || is.getType() == Material.AIR ? "" : serialize(is));
        }
        return sb.toString();
    }

    private List<ItemStack> deserializeInventory(String data) {
        ObjectArrayList<ItemStack> list = new ObjectArrayList<>();
        if (data == null || data.isEmpty()) {
            return list;
        }
        String[] parts = data.split(";", -1);
        for (String part : parts) {
            if (part.isEmpty()) {
                list.add(null);
            } else {
                list.add(deserialize(part));
            }
        }
        return list;
    }

    private Connection open() throws SQLException {
        if (dataSource == null) {
            throw new SQLException("DataSource не инициализирован");
        }
        return dataSource.getConnection();
    }

    private String serialize(ItemStack item) {
        return Base64.getEncoder().encodeToString(item.serializeAsBytes());
    }

    private ItemStack deserialize(String data){
        return ItemStack.deserializeBytes(Base64.getDecoder().decode(data));
    }
